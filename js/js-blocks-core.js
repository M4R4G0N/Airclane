"use strict";

// JS Blocks — core engine (no DOM). Tokenizes/parses a focused JS subset into
// a block tree (Program.body of statement nodes) and generates JS text back
// from that tree. Anything outside the supported subset becomes a RawCode
// block (node.invalid === true) instead of failing the whole conversion, so
// partially-unsupported scripts still round-trip.

const JS_BLOCKS_KEYWORDS = new Set([
  'const', 'let', 'var', 'if', 'else', 'for', 'while', 'function', 'return',
  'break', 'continue', 'true', 'false', 'null', 'undefined', 'of', 'in', 'new', 'typeof',
  // outside the supported subset — tokenized as keywords (not names) so the
  // statement parser can reject them up front and recover the statement
  // whole, as one RawCode block, instead of shredding it into bogus
  // identifier statements ('class;' 'Foo;' ...)
  'class', 'extends', 'async', 'await', 'try', 'catch', 'finally', 'switch',
  'case', 'default', 'do', 'throw', 'import', 'export', 'instanceof', 'void',
  'delete', 'yield'
]);

const JS_BLOCKS_TOKEN_SPECS = [
  ['whitespace', /^\s+/],
  ['comment', /^\/\/[^\n]*/],
  ['comment', /^\/\*[\s\S]*?\*\//],
  ['string', /^'(?:\\.|[^'\\])*'/],
  ['string', /^"(?:\\.|[^"\\])*"/],
  // template literals are captured whole (no ${...} parsing) and regenerated byte-for-byte
  ['template', /^`(?:\\.|[^`\\])*`/],
  ['number', /^\d+(?:\.\d+)?(?:[eE][+-]?\d+)?/],
  ['punct', /^(===|!==|==|!=|<=|>=|&&|\|\||\+=|-=|\*=|\/=|%=|=>|\+\+|--|\.\.\.|[{}()[\];,.:?=<>+\-*/%!&|])/],
  ['name', /^[A-Za-z_$][A-Za-z0-9_$]*/]
];

function tokenizeJsBlocks(source) {
  const tokens = [];
  let pos = 0;
  while (pos < source.length) {
    const slice = source.slice(pos);
    let matched = false;
    for (const [type, regex] of JS_BLOCKS_TOKEN_SPECS) {
      const m = regex.exec(slice);
      if (!m) continue;
      matched = true;
      const value = m[0];
      if (type !== 'whitespace' && type !== 'comment') {
        const tokType = (type === 'name' && JS_BLOCKS_KEYWORDS.has(value)) ? 'keyword' : type;
        tokens.push({ type: tokType, value, start: pos, end: pos + value.length });
      }
      pos += value.length;
      break;
    }
    if (!matched) throw new Error('Unexpected character "' + source[pos] + '" at ' + pos);
  }
  tokens.push({ type: 'eof', value: '', start: pos, end: pos });
  return tokens;
}

// ---------- parser state helpers ----------

function jsBlocksCreateState(source) {
  return { source, tokens: tokenizeJsBlocks(source), pos: 0 };
}
function jsBlocksCurrent(state) { return state.tokens[state.pos]; }
function jsBlocksPeek(state, offset) { return state.tokens[state.pos + offset]; }
function jsBlocksAdvance(state) { return state.tokens[state.pos++]; }
function jsBlocksAtEnd(state) { return jsBlocksCurrent(state).type === 'eof'; }
function jsBlocksCheck(state, type, value) {
  const tok = jsBlocksCurrent(state);
  if (tok.type !== type) return false;
  if (value !== undefined && tok.value !== value) return false;
  return true;
}
function jsBlocksMatch(state, type, value) {
  return jsBlocksCheck(state, type, value) ? jsBlocksAdvance(state) : null;
}
function jsBlocksExpect(state, type, value) {
  const tok = jsBlocksMatch(state, type, value);
  if (!tok) {
    const got = jsBlocksCurrent(state);
    throw new Error('Expected ' + (value || type) + ' but got "' + got.value + '" at ' + got.start);
  }
  return tok;
}

// ---------- statement list with per-statement error recovery ----------

function jsBlocksParseStatementList(state, terminatorValue) {
  const body = [];
  while (!jsBlocksAtEnd(state) && !(terminatorValue && jsBlocksCheck(state, 'punct', terminatorValue))) {
    const startPos = state.pos;
    try {
      const stmt = jsBlocksParseStatement(state);
      // a comma-separated `let a = 1, b = 2;` parses as several sibling
      // declarations (see jsBlocksParseVariableDeclaration) instead of one
      // compound node — there's no "declare 2 vars" block, only one-per-line.
      if (Array.isArray(stmt)) body.push.apply(body, stmt);
      else body.push(stmt);
    } catch (err) {
      state.pos = startPos;
      body.push({ type: 'RawCode', code: jsBlocksRecoverRawStatement(state), invalid: true });
    }
  }
  return body;
}

function jsBlocksRecoverRawStatement(state) {
  const startTok = jsBlocksCurrent(state);
  let depth = 0;
  let sawBrace = false;
  let endTok = startTok;
  while (!jsBlocksAtEnd(state)) {
    const tok = jsBlocksCurrent(state);
    if (tok.type === 'punct' && '{(['.includes(tok.value)) {
      depth++;
      if (tok.value === '{') sawBrace = true;
    } else if (tok.type === 'punct' && '})]'.includes(tok.value)) {
      if (depth === 0) break;
      depth--;
    }
    endTok = tok;
    jsBlocksAdvance(state);
    if (depth === 0 && tok.type === 'punct' && tok.value === ';') break;
    // keyword-led statements like `class X { ... }` don't end in ';' — a
    // balanced closing brace ends them. Don't stop when else/catch/finally
    // continues the same statement (a dangling `else` would be a syntax error).
    if (depth === 0 && sawBrace && tok.type === 'punct' && tok.value === '}') {
      const next = jsBlocksCurrent(state);
      if (!(next && next.type === 'keyword' && ['else', 'catch', 'finally'].includes(next.value))) break;
    }
  }
  return state.source.slice(startTok.start, endTok.end);
}

// ---------- statements ----------

function jsBlocksParseStatement(state) {
  const tok = jsBlocksCurrent(state);
  if (tok.type === 'keyword') {
    switch (tok.value) {
      case 'const': case 'let': case 'var': return jsBlocksParseVariableDeclaration(state);
      case 'if': return jsBlocksParseIf(state);
      case 'for': return jsBlocksParseFor(state);
      case 'while': return jsBlocksParseWhile(state);
      case 'function': return jsBlocksParseFunctionDeclaration(state);
      case 'return': return jsBlocksParseReturn(state);
      case 'break': jsBlocksAdvance(state); jsBlocksMatch(state, 'punct', ';'); return { type: 'Break' };
      case 'continue': jsBlocksAdvance(state); jsBlocksMatch(state, 'punct', ';'); return { type: 'Continue' };
    }
    // keyword-led statements outside the subset (class, async, import, try,
    // switch...) must never fall through to the expression parser — it would
    // shred them into bogus identifier statements ('class;' 'Foo;' ...) and
    // the code would NOT survive the round-trip. Throw so the caller's
    // recovery grabs the whole statement as one intact RawCode block.
    throw new Error('unsupported statement keyword: ' + tok.value);
  }
  return jsBlocksParseExpressionStatement(state);
}

function jsBlocksParseVariableDeclaration(state) {
  const kind = jsBlocksAdvance(state).value;
  const decls = [];
  do {
    const name = jsBlocksExpect(state, 'name').value;
    let init = null;
    if (jsBlocksMatch(state, 'punct', '=')) init = jsBlocksParseExpression(state);
    decls.push({ type: 'VariableDeclaration', kind, name, init });
  } while (jsBlocksMatch(state, 'punct', ','));
  jsBlocksMatch(state, 'punct', ';');
  return decls.length === 1 ? decls[0] : decls;
}

function jsBlocksParseBlock(state) {
  jsBlocksExpect(state, 'punct', '{');
  const body = jsBlocksParseStatementList(state, '}');
  jsBlocksExpect(state, 'punct', '}');
  return body;
}

function jsBlocksParseIf(state) {
  jsBlocksAdvance(state);
  jsBlocksExpect(state, 'punct', '(');
  const test = jsBlocksParseExpression(state);
  jsBlocksExpect(state, 'punct', ')');
  const consequent = jsBlocksParseBlock(state);
  let alternate = null;
  if (jsBlocksCheck(state, 'keyword', 'else')) {
    jsBlocksAdvance(state);
    alternate = jsBlocksCheck(state, 'keyword', 'if') ? [jsBlocksParseIf(state)] : jsBlocksParseBlock(state);
  }
  return { type: 'If', test, consequent, alternate };
}

function jsBlocksParseFor(state) {
  jsBlocksAdvance(state);
  jsBlocksExpect(state, 'punct', '(');

  if (jsBlocksCheck(state, 'keyword') && ['let', 'const', 'var'].includes(jsBlocksCurrent(state).value)) {
    const savedPos = state.pos;
    const kind = jsBlocksAdvance(state).value;
    const name = jsBlocksExpect(state, 'name').value;
    if (jsBlocksCheck(state, 'keyword', 'of') || jsBlocksCheck(state, 'keyword', 'in')) {
      const iterKind = jsBlocksAdvance(state).value;
      const iterable = jsBlocksParseExpression(state);
      jsBlocksExpect(state, 'punct', ')');
      const body = jsBlocksParseBlock(state);
      return { type: 'ForOf', kind, name, iterKind, iterable, body };
    }
    state.pos = savedPos;
  }

  const init = jsBlocksCheck(state, 'punct', ';') ? null : jsBlocksParseForInit(state);
  jsBlocksExpect(state, 'punct', ';');
  const test = jsBlocksCheck(state, 'punct', ';') ? null : jsBlocksParseExpression(state);
  jsBlocksExpect(state, 'punct', ';');
  const update = jsBlocksCheck(state, 'punct', ')') ? null : jsBlocksParseExpression(state);
  jsBlocksExpect(state, 'punct', ')');
  const body = jsBlocksParseBlock(state);
  return { type: 'For', init, test, update, body };
}

function jsBlocksParseForInit(state) {
  if (jsBlocksCheck(state, 'keyword') && ['let', 'const', 'var'].includes(jsBlocksCurrent(state).value)) {
    const kind = jsBlocksAdvance(state).value;
    const name = jsBlocksExpect(state, 'name').value;
    let init = null;
    if (jsBlocksMatch(state, 'punct', '=')) init = jsBlocksParseExpression(state);
    return { type: 'VariableDeclaration', kind, name, init };
  }
  return { type: 'ExpressionStatement', expression: jsBlocksParseExpression(state) };
}

function jsBlocksParseWhile(state) {
  jsBlocksAdvance(state);
  jsBlocksExpect(state, 'punct', '(');
  const test = jsBlocksParseExpression(state);
  jsBlocksExpect(state, 'punct', ')');
  const body = jsBlocksParseBlock(state);
  return { type: 'While', test, body };
}

function jsBlocksParseFunctionDeclaration(state) {
  jsBlocksAdvance(state);
  const name = jsBlocksExpect(state, 'name').value;
  const params = jsBlocksParseParamList(state);
  const body = jsBlocksParseBlock(state);
  return { type: 'FunctionDeclaration', name, params, body };
}

function jsBlocksParseParamList(state) {
  jsBlocksExpect(state, 'punct', '(');
  const params = [];
  while (!jsBlocksCheck(state, 'punct', ')')) {
    params.push(jsBlocksExpect(state, 'name').value);
    if (!jsBlocksMatch(state, 'punct', ',')) break;
  }
  jsBlocksExpect(state, 'punct', ')');
  return params;
}

function jsBlocksParseReturn(state) {
  jsBlocksAdvance(state);
  let argument = null;
  if (!jsBlocksCheck(state, 'punct', ';') && !jsBlocksCheck(state, 'punct', '}')) {
    argument = jsBlocksParseExpression(state);
  }
  jsBlocksMatch(state, 'punct', ';');
  return { type: 'Return', argument };
}

function jsBlocksParseExpressionStatement(state) {
  const expression = jsBlocksParseExpression(state);
  jsBlocksMatch(state, 'punct', ';');
  return jsBlocksTryAsForEach(expression) || { type: 'ExpressionStatement', expression };
}

// `list.forEach((item[, index]) => { ... })` is the most common iteration
// idiom in real-world JS, and reads exactly like a loop — so it gets its own
// block (ForEach) with a real, draggable body, instead of showing up as one
// flat "call expression" with the whole callback squashed into text. The
// callback's params have no let/const/var keyword (they're just parameter
// names), unlike a real for...of.
function jsBlocksTryAsForEach(expr) {
  if (expr.type !== 'CallExpression') return null;
  const callee = expr.callee;
  if (callee.type !== 'MemberExpression' || callee.computed || callee.property !== 'forEach') return null;
  if (expr.arguments.length !== 1) return null;
  const fn = expr.arguments[0];
  if ((fn.type !== 'ArrowFunctionExpression' && fn.type !== 'FunctionExpression') || fn.expressionBody) return null;
  if (fn.params.length < 1 || fn.params.length > 2) return null;
  return { type: 'ForEach', iterable: callee.object, itemName: fn.params[0], indexName: fn.params[1] || null, body: fn.body };
}

// ---------- expressions (precedence climbing) ----------

function jsBlocksParseExpression(state) { return jsBlocksParseAssignment(state); }

function jsBlocksParseAssignment(state) {
  const left = jsBlocksParseLogicalOr(state);
  const ops = ['=', '+=', '-=', '*=', '/=', '%='];
  if (jsBlocksCurrent(state).type === 'punct' && ops.includes(jsBlocksCurrent(state).value)) {
    const operator = jsBlocksAdvance(state).value;
    const right = jsBlocksParseAssignment(state);
    return { type: 'AssignmentExpression', operator, left, right };
  }
  return left;
}

function jsBlocksBinaryLevel(parseNext, ops) {
  return function (state) {
    let left = parseNext(state);
    while (jsBlocksCurrent(state).type === 'punct' && ops.includes(jsBlocksCurrent(state).value)) {
      const operator = jsBlocksAdvance(state).value;
      const right = parseNext(state);
      left = { type: ops.includes('&&') || ops.includes('||') ? 'LogicalExpression' : 'BinaryExpression', operator, left, right };
    }
    return left;
  };
}

function jsBlocksParseUnaryLevel(state) {
  return jsBlocksParseUnary(state);
}

const jsBlocksParseEquality = jsBlocksBinaryLevel((s) => jsBlocksParseRelational(s), ['===', '!==', '==', '!=']);
function jsBlocksParseRelational(state) { return jsBlocksBinaryLevel((s) => jsBlocksParseAdditive(s), ['<', '>', '<=', '>='])(state); }
function jsBlocksParseAdditive(state) { return jsBlocksBinaryLevel((s) => jsBlocksParseMultiplicative(s), ['+', '-'])(state); }
function jsBlocksParseMultiplicative(state) { return jsBlocksBinaryLevel((s) => jsBlocksParseUnaryLevel(s), ['*', '/', '%'])(state); }
function jsBlocksParseLogicalAnd(state) { return jsBlocksBinaryLevel((s) => jsBlocksParseEquality(s), ['&&'])(state); }
function jsBlocksParseLogicalOr(state) { return jsBlocksBinaryLevel((s) => jsBlocksParseLogicalAnd(s), ['||'])(state); }

function jsBlocksParseUnary(state) {
  const tok = jsBlocksCurrent(state);
  const isUnaryPunct = tok.type === 'punct' && ['!', '-', '+'].includes(tok.value);
  const isUpdatePunct = tok.type === 'punct' && (tok.value === '++' || tok.value === '--');
  const isTypeof = tok.type === 'keyword' && tok.value === 'typeof';
  if (isUpdatePunct) {
    const operator = jsBlocksAdvance(state).value;
    const argument = jsBlocksParseUnary(state);
    return { type: 'UpdateExpression', operator, argument, prefix: true };
  }
  if (isUnaryPunct || isTypeof) {
    const operator = jsBlocksAdvance(state).value;
    const argument = jsBlocksParseUnary(state);
    return { type: 'UnaryExpression', operator, argument };
  }
  return jsBlocksParseCallMemberChain(state);
}

function jsBlocksParseCallMemberChain(state) {
  let expr = jsBlocksParsePrimary(state);
  while (true) {
    if (jsBlocksCheck(state, 'punct', '.')) {
      jsBlocksAdvance(state);
      const property = jsBlocksExpect(state, 'name').value;
      expr = { type: 'MemberExpression', object: expr, property, computed: false };
    } else if (jsBlocksCheck(state, 'punct', '[')) {
      jsBlocksAdvance(state);
      const property = jsBlocksParseExpression(state);
      jsBlocksExpect(state, 'punct', ']');
      expr = { type: 'MemberExpression', object: expr, property, computed: true };
    } else if (jsBlocksCheck(state, 'punct', '(')) {
      expr = { type: 'CallExpression', callee: expr, arguments: jsBlocksParseArgList(state) };
    } else {
      break;
    }
  }
  if (jsBlocksCheck(state, 'punct', '++') || jsBlocksCheck(state, 'punct', '--')) {
    const operator = jsBlocksAdvance(state).value;
    expr = { type: 'UpdateExpression', operator, argument: expr, prefix: false };
  }
  return expr;
}

function jsBlocksParseArgList(state) {
  jsBlocksExpect(state, 'punct', '(');
  const args = [];
  while (!jsBlocksCheck(state, 'punct', ')')) {
    args.push(jsBlocksParseExpression(state));
    if (!jsBlocksMatch(state, 'punct', ',')) break;
  }
  jsBlocksExpect(state, 'punct', ')');
  return args;
}

function jsBlocksParsePrimary(state) {
  const tok = jsBlocksCurrent(state);

  if (tok.type === 'number') { jsBlocksAdvance(state); return { type: 'Literal', value: Number(tok.value), literalType: 'number' }; }
  if (tok.type === 'string') { jsBlocksAdvance(state); return { type: 'Literal', value: jsBlocksUnescapeString(tok.value), literalType: 'string' }; }
  if (tok.type === 'template') { jsBlocksAdvance(state); return { type: 'TemplateLiteral', raw: tok.value }; }
  if (tok.type === 'keyword' && tok.value === 'true') { jsBlocksAdvance(state); return { type: 'Literal', value: true, literalType: 'boolean' }; }
  if (tok.type === 'keyword' && tok.value === 'false') { jsBlocksAdvance(state); return { type: 'Literal', value: false, literalType: 'boolean' }; }
  if (tok.type === 'keyword' && tok.value === 'null') { jsBlocksAdvance(state); return { type: 'Literal', value: null, literalType: 'null' }; }
  if (tok.type === 'keyword' && tok.value === 'undefined') { jsBlocksAdvance(state); return { type: 'Identifier', name: 'undefined' }; }

  if (tok.type === 'keyword' && tok.value === 'new') {
    jsBlocksAdvance(state);
    const callee = jsBlocksParseCallMemberChain(state);
    if (callee.type === 'CallExpression') return { type: 'NewExpression', callee: callee.callee, arguments: callee.arguments };
    return { type: 'NewExpression', callee, arguments: [] };
  }

  if (tok.type === 'keyword' && tok.value === 'function') return jsBlocksParseFunctionExpression(state);

  // bare single-param arrow: `x => ...` — one token of lookahead past the
  // identifier is enough to tell it apart from a plain Identifier.
  if (tok.type === 'name' && jsBlocksPeek(state, 1).type === 'punct' && jsBlocksPeek(state, 1).value === '=>') {
    jsBlocksAdvance(state);
    jsBlocksAdvance(state); // =>
    return jsBlocksParseArrowBody(state, [tok.value]);
  }

  if (tok.type === 'name') { jsBlocksAdvance(state); return { type: 'Identifier', name: tok.value }; }

  if (tok.type === 'punct' && tok.value === '(') {
    // `(a, b)` is ambiguous with arrow-function params until we see whether
    // `=>` follows the closing paren — try that reading first and roll back
    // to a plain parenthesized expression if it doesn't pan out.
    const arrow = jsBlocksTryParseArrowFunction(state);
    if (arrow) return arrow;
    jsBlocksAdvance(state);
    const expr = jsBlocksParseExpression(state);
    jsBlocksExpect(state, 'punct', ')');
    return expr;
  }

  if (tok.type === 'punct' && tok.value === '[') return jsBlocksParseArrayExpression(state);
  if (tok.type === 'punct' && tok.value === '{') return jsBlocksParseObjectExpression(state);

  throw new Error('Unexpected token "' + tok.value + '" at ' + tok.start);
}

function jsBlocksTryParseArrowFunction(state) {
  const savedPos = state.pos;
  try {
    const params = jsBlocksParseParamList(state);
    if (jsBlocksCheck(state, 'punct', '=>')) {
      jsBlocksAdvance(state);
      return jsBlocksParseArrowBody(state, params);
    }
  } catch (err) {
    // not arrow params after all (e.g. a real parenthesized expression like
    // `(1 + 2)`) — fall through and let the caller retry as one.
  }
  state.pos = savedPos;
  return null;
}

function jsBlocksParseArrowBody(state, params) {
  if (jsBlocksCheck(state, 'punct', '{')) {
    return { type: 'ArrowFunctionExpression', params, body: jsBlocksParseBlock(state), expressionBody: false };
  }
  return { type: 'ArrowFunctionExpression', params, body: jsBlocksParseAssignment(state), expressionBody: true };
}

function jsBlocksUnescapeString(raw) {
  const quote = raw[0];
  return raw.slice(1, -1).replace(/\\(.)/g, function (_, ch) {
    if (ch === 'n') return '\n';
    if (ch === 't') return '\t';
    if (ch === '\\') return '\\';
    if (ch === quote) return quote;
    return ch;
  });
}

function jsBlocksParseFunctionExpression(state) {
  jsBlocksAdvance(state);
  const name = jsBlocksCheck(state, 'name') ? jsBlocksAdvance(state).value : null;
  const params = jsBlocksParseParamList(state);
  const body = jsBlocksParseBlock(state);
  return { type: 'FunctionExpression', name, params, body };
}

function jsBlocksParseArrayExpression(state) {
  jsBlocksExpect(state, 'punct', '[');
  const elements = [];
  while (!jsBlocksCheck(state, 'punct', ']')) {
    elements.push(jsBlocksParseExpression(state));
    if (!jsBlocksMatch(state, 'punct', ',')) break;
  }
  jsBlocksExpect(state, 'punct', ']');
  return { type: 'ArrayExpression', elements };
}

function jsBlocksParseObjectExpression(state) {
  jsBlocksExpect(state, 'punct', '{');
  const properties = [];
  while (!jsBlocksCheck(state, 'punct', '}')) {
    const key = jsBlocksCheck(state, 'string')
      ? jsBlocksUnescapeString(jsBlocksAdvance(state).value)
      : jsBlocksExpect(state, 'name').value;
    const value = jsBlocksMatch(state, 'punct', ':') ? jsBlocksParseExpression(state) : { type: 'Identifier', name: key };
    properties.push({ key, value });
    if (!jsBlocksMatch(state, 'punct', ',')) break;
  }
  jsBlocksExpect(state, 'punct', '}');
  return { type: 'ObjectExpression', properties };
}

// ---------- public: code -> blocks ----------

function parseJsToBlocks(source) {
  let state;
  try {
    state = jsBlocksCreateState(source);
  } catch (err) {
    // a character outside the supported subset (e.g. a regex literal) breaks
    // tokenization for the whole source — fall back to one raw block instead
    // of failing the conversion entirely.
    return { type: 'Program', body: [{ type: 'RawCode', code: source, invalid: true }] };
  }
  const body = jsBlocksParseStatementList(state, null);
  return { type: 'Program', body };
}

// ---------- public: blocks -> code ----------

function jsBlocksIndent(level) { return '  '.repeat(level); }

function generateBlocksToCode(program) {
  return program.body.map((stmt) => jsBlocksGenerateStatement(stmt, 0)).join('\n');
}

function jsBlocksGenerateStatement(node, level) {
  const pad = jsBlocksIndent(level);
  switch (node.type) {
    case 'RawCode':
      return pad + node.code;
    case 'VariableDeclaration':
      return pad + node.kind + ' ' + node.name + (node.init ? ' = ' + jsBlocksGenerateExpression(node.init) : '') + ';';
    case 'ExpressionStatement':
      return pad + jsBlocksGenerateExpression(node.expression) + ';';
    case 'If': {
      let out = pad + 'if (' + jsBlocksGenerateExpression(node.test) + ') {\n';
      out += node.consequent.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '}';
      if (node.alternate) {
        if (node.alternate.length === 1 && node.alternate[0].type === 'If') {
          out += ' else ' + jsBlocksGenerateStatement(node.alternate[0], level).trim();
        } else {
          out += ' else {\n' + node.alternate.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n') + '\n' + pad + '}';
        }
      }
      return out;
    }
    case 'For': {
      const initStr = node.init ? jsBlocksGenerateForClause(node.init) : '';
      const testStr = node.test ? jsBlocksGenerateExpression(node.test) : '';
      const updateStr = node.update ? jsBlocksGenerateExpression(node.update) : '';
      let out = pad + 'for (' + initStr + '; ' + testStr + '; ' + updateStr + ') {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '}';
      return out;
    }
    case 'ForOf': {
      let out = pad + 'for (' + node.kind + ' ' + node.name + ' ' + node.iterKind + ' ' + jsBlocksGenerateExpression(node.iterable) + ') {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '}';
      return out;
    }
    case 'While': {
      let out = pad + 'while (' + jsBlocksGenerateExpression(node.test) + ') {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '}';
      return out;
    }
    case 'ForEach': {
      const params = node.indexName ? node.itemName + ', ' + node.indexName : node.itemName;
      let out = pad + jsBlocksGenerateExpression(node.iterable) + '.forEach((' + params + ') => {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '});';
      return out;
    }
    case 'FunctionDeclaration': {
      let out = pad + 'function ' + node.name + '(' + node.params.join(', ') + ') {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, level + 1)).join('\n');
      out += '\n' + pad + '}';
      return out;
    }
    case 'Return':
      return pad + 'return' + (node.argument ? ' ' + jsBlocksGenerateExpression(node.argument) : '') + ';';
    case 'Break': return pad + 'break;';
    case 'Continue': return pad + 'continue;';
    default:
      throw new Error('Unknown statement type: ' + node.type);
  }
}

function jsBlocksGenerateForClause(node) {
  if (node.type === 'VariableDeclaration') {
    return node.kind + ' ' + node.name + (node.init ? ' = ' + jsBlocksGenerateExpression(node.init) : '');
  }
  return jsBlocksGenerateExpression(node.expression);
}

function jsBlocksGenerateExpression(node) {
  switch (node.type) {
    case 'Identifier': return node.name;
    case 'Literal':
      if (node.literalType === 'string') {
        return "'" + String(node.value).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n') + "'";
      }
      if (node.literalType === 'null') return 'null';
      return String(node.value);
    case 'ArrayExpression':
      return '[' + node.elements.map(jsBlocksGenerateExpression).join(', ') + ']';
    case 'ObjectExpression':
      return '{ ' + node.properties.map((p) => p.key + ': ' + jsBlocksGenerateExpression(p.value)).join(', ') + ' }';
    case 'BinaryExpression':
    case 'LogicalExpression':
    case 'AssignmentExpression':
      return jsBlocksGenerateExpression(node.left) + ' ' + node.operator + ' ' + jsBlocksGenerateExpression(node.right);
    case 'UnaryExpression':
      return node.operator + (node.operator === 'typeof' ? ' ' : '') + jsBlocksGenerateExpression(node.argument);
    case 'UpdateExpression':
      return node.prefix
        ? node.operator + jsBlocksGenerateExpression(node.argument)
        : jsBlocksGenerateExpression(node.argument) + node.operator;
    case 'TemplateLiteral':
      return node.raw;
    case 'CallExpression':
      return jsBlocksGenerateExpression(node.callee) + '(' + node.arguments.map(jsBlocksGenerateExpression).join(', ') + ')';
    case 'NewExpression':
      return 'new ' + jsBlocksGenerateExpression(node.callee) + '(' + node.arguments.map(jsBlocksGenerateExpression).join(', ') + ')';
    case 'MemberExpression':
      return node.computed
        ? jsBlocksGenerateExpression(node.object) + '[' + jsBlocksGenerateExpression(node.property) + ']'
        : jsBlocksGenerateExpression(node.object) + '.' + node.property;
    case 'FunctionExpression': {
      let out = 'function' + (node.name ? ' ' + node.name : '') + '(' + node.params.join(', ') + ') {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, 1)).join('\n');
      out += '\n}';
      return out;
    }
    case 'ArrowFunctionExpression': {
      const params = '(' + node.params.join(', ') + ')';
      if (node.expressionBody) return params + ' => ' + jsBlocksGenerateExpression(node.body);
      let out = params + ' => {\n';
      out += node.body.map((s) => jsBlocksGenerateStatement(s, 1)).join('\n');
      out += '\n}';
      return out;
    }
    default:
      throw new Error('Unknown expression type: ' + node.type);
  }
}

// counts RawCode (unconverted) blocks anywhere in the tree, used by the UI to
// flag a script as "not fully converted" per the fallback policy.
function countJsBlocksInvalid(program) {
  let count = 0;
  function walkStatements(list) {
    for (const node of list) {
      if (node.type === 'RawCode') { count++; continue; }
      if (node.consequent) walkStatements(node.consequent);
      if (node.alternate) walkStatements(node.alternate);
      if (node.body) walkStatements(node.body);
    }
  }
  walkStatements(program.body);
  return count;
}
